        <h3>Blade Work</h3>
        <p>Proper blade technique is essential for both attack and defense:</p>

        <h3>Offensive Actions</h3>
        <ul>
            <li><strong>Direct Attack:</strong> A straight thrust toward the target without any blade preparation</li>
            <li><strong>Disengage:</strong> Moving the blade around the opponent's blade to hit the opposite side</li>
            <li><strong>Coupé:</strong> Passing the blade over the opponent's point to attack the opposite line</li>
            <li><strong>Beat Attack:</strong> Striking the opponent's blade sharply before attacking</li>
            <li><strong>Compound Attack:</strong> An attack composed of one or more feints followed by a final action</li>
        </ul>

        <h3>Defensive Actions</h3>
        <ul>
            <li><strong>Parry:</strong> Deflecting the opponent's blade with your own to block an attack. There are eight basic parry positions</li>
            <li><strong>Riposte:</strong> An offensive action immediately following a successful parry</li>
            <li><strong>Counter-Riposte:</strong> An offensive action following a parry of the opponent's riposte</li>
            <li><strong>Distance:</strong> Moving out of attacking range to avoid a touch</li>
        </ul>

        <h3>Tactical Concepts</h3>
        <div class="content">
            <p><strong>Distance Management:</strong> Maintaining optimal distance from your opponent - close enough to attack but far enough to defend.</p>
            
            <p><strong>Timing:</strong> Executing actions at the precise moment to catch your opponent off guard or exploit their movements.</p>
            
            <p><strong>Preparation:</strong> Actions designed to create openings or provoke reactions from your opponent before launching an attack.</p>
            
            <p><strong>Right of Way (Priority):</strong> In foil and sabre, understanding and controlling priority is crucial for scoring touches.</p>
        </div>

        <h3>Training Tips</h3>
